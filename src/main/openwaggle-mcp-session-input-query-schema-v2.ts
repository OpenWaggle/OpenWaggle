const sessionExportManifestSchemaV2 = Schema.Struct({
  schemaVersion: literal(1),
  sessionId: mcpSessionIdSchemaV2,
  title: mcpSessionTitleSchemaV2,
  branchScope: enumeration('active-branch', 'tree'),
  activeBranchId: Schema.NullOr(mcpSessionIdSchemaV2),
  selectedBranchId: Schema.NullOr(mcpSessionIdSchemaV2),
  snapshot: Schema.Struct({
    nodeHighWaterMark: revision,
    stateRevision: revision,
    queueRevision: revision,
    capturedAt: revision,
    nodeMutationRevision: optional(revision),
    selectedHeadNodeId: optional(mcpSessionIdSchemaV2),
  }),
  activeRunId: Schema.NullOr(mcpSessionIdSchemaV2),
  activeTurnIncomplete: Schema.Boolean,
  queue: Schema.Struct({
    state: enumeration('running', 'paused'),
    pendingCount: revision,
    bodyScope: enumeration('included', 'omitted-by-choice'),
    omittedBodyCount: revision,
    items: Schema.Array(
      Schema.Struct({
        followUpId: mcpSessionIdSchemaV2,
        position: revision,
        createdAt: revision,
        deliveryState: enumeration('pending', 'needs_attention'),
        attentionReason: optional(enumeration('profile_revoked', 'authority_changed')),
        intent: optional(jsonValue),
      }),
    ),
  }),
})

