import { isCodexReport } from './watch-bots'
import type {
  IssueComment,
  PullRequestState,
  Review,
  ReviewThread,
  ThreadComment,
} from './watch-model'

const BABYSIT_MARKER = '<!-- babysit -->'
const BABYSIT_NOTICE = 'This was generated by AI via the babysit skill.'
const REPLY_TO_PATTERN = /<!--\s*babysit:reply-to:([^>]*?)\s*-->/g
const HIDDEN_MARKER_PATTERN = /<!--[\s\S]*?-->/
/** Bots whose comments are status reports (deploy previews), never review feedback. */
const REPORT_BOTS = new Set(['cloudflare-workers-and-pages', 'netlify', 'vercel'])
const MAX_BODY_LENGTH = 4000
const EXCERPT_LENGTH = 200

export interface OpenItem {
  readonly author: string
  readonly body: string
  /** Inline review threads are `thread`; conversation comments `comment`; review bodies `review`. */
  readonly kind: 'comment' | 'review' | 'thread'
  readonly line: number | undefined
  readonly outdated: boolean
  readonly path: string | undefined
  readonly replies: readonly {
    readonly author: string
    readonly excerpt: string
    readonly fromBabysit: boolean
  }[]
  /**
   * How to answer. Threads: POST a reply to `repos/{owner}/{repo}/pulls/<n>/comments/<id>/replies`.
   * Comments and reviews: a new PR comment carrying this marker, which closes the item.
   */
  readonly reply: { readonly commentId: number } | { readonly marker: string }
  readonly url: string
}

export interface AnsweredThread {
  readonly author: string
  readonly url: string
}

function truncate(text: string, length: number) {
  return text.length > length ? `${text.slice(0, length)}…` : text
}

function isBabysitNote(body: string) {
  return body.includes(BABYSIT_MARKER) || body.includes(BABYSIT_NOTICE)
}

function isBabysitReply(
  comment: { readonly author: { readonly login: string }; readonly body: string },
  viewer: string,
) {
  return comment.author.login === viewer && isBabysitNote(comment.body)
}

/** `comment-<id>` and `review-<id>` tokens the viewer's babysit replies have already answered. */
function answeredTokens(comments: readonly IssueComment[], viewer: string) {
  const tokens = new Set<string>()
  for (const comment of comments.filter((candidate) => isBabysitReply(candidate, viewer))) {
    for (const match of comment.body.matchAll(REPLY_TO_PATTERN)) {
      for (const token of (match[1] ?? '').split(/[\s,]+/)) {
        tokens.add(token)
      }
    }
  }
  return tokens
}

/** The viewer's tool output (babysit notes, managed reports) and bot status reports are not items. */
function isReportComment(comment: IssueComment, viewer: string) {
  if (comment.author.login === viewer) {
    return isBabysitNote(comment.body) || HIDDEN_MARKER_PATTERN.test(comment.body)
  }
  if (!comment.author.isBot) {
    return false
  }
  return (
    REPORT_BOTS.has(comment.author.login) ||
    isCodexReport(comment) ||
    HIDDEN_MARKER_PATTERN.test(comment.body)
  )
}

function replySummary(comments: readonly ThreadComment[], viewer: string) {
  return comments.map((comment) => ({
    author: comment.author.login,
    excerpt: truncate(comment.body.trim(), EXCERPT_LENGTH),
    fromBabysit: isBabysitReply(comment, viewer),
  }))
}

function threadItem(thread: ReviewThread, first: ThreadComment, viewer: string): OpenItem {
  return {
    author: first.author.login,
    body: truncate(first.body, MAX_BODY_LENGTH),
    kind: 'thread',
    line: thread.line,
    outdated: thread.isOutdated,
    path: thread.path,
    replies: replySummary(thread.comments.slice(1), viewer),
    reply: { commentId: first.id },
    url: first.url,
  }
}

function plainItem(entry: IssueComment | Review, kind: 'comment' | 'review'): OpenItem {
  return {
    author: entry.author.login,
    body: truncate(entry.body, MAX_BODY_LENGTH),
    kind,
    line: undefined,
    outdated: false,
    path: undefined,
    replies: [],
    reply: { marker: `<!-- babysit:reply-to:${kind}-${String(entry.id)} -->` },
    url: entry.url,
  }
}

function collectThreads(threads: readonly ReviewThread[], viewer: string) {
  const openItems: OpenItem[] = []
  const answeredThreads: AnsweredThread[] = []
  for (const thread of threads) {
    const first = thread.comments.at(0)
    const latest = thread.comments.at(-1)
    if (thread.isResolved || first === undefined || latest === undefined) {
      continue
    }
    if (isBabysitReply(first, viewer) && thread.comments.length === 1) {
      continue
    }
    if (isBabysitReply(latest, viewer)) {
      answeredThreads.push({ author: first.author.login, url: first.url })
      continue
    }
    openItems.push(threadItem(thread, first, viewer))
  }
  return { answeredThreads, openItems }
}

/**
 * Review feedback nobody has answered yet, from people and bots alike. A thread is closed when it
 * is resolved (the maintainer's call, never the babysitter's) or its latest comment is a babysit
 * reply; a later comment from anyone opens it again. GitHub conversation comments have no threads,
 * so a babysit reply names the comments it answers with a `babysit:reply-to` marker.
 */
export function collectComments(state: PullRequestState) {
  const { viewer } = state
  const { answeredThreads, openItems } = collectThreads(state.threads, viewer)
  const answered = answeredTokens(state.comments, viewer)
  for (const comment of state.comments) {
    if (!isReportComment(comment, viewer) && !answered.has(`comment-${String(comment.id)}`)) {
      openItems.push(plainItem(comment, 'comment'))
    }
  }
  for (const review of state.reviews) {
    const hasBody = review.body.trim().length > 0
    // Bot review bodies are receipts or summaries; their findings arrive as inline threads.
    if (
      hasBody &&
      !review.author.isBot &&
      !isBabysitReply(review, viewer) &&
      !answered.has(`review-${String(review.id)}`)
    ) {
      openItems.push(plainItem(review, 'review'))
    }
  }
  return { answeredThreads, openItems }
}
