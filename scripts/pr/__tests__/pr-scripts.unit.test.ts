import { describe, expect, it } from 'vitest'
import { GITHUB_COMMENT_MAX_CHARACTERS, parseNameStatus, renderBlastRadius } from '../blast-radius'
import { classifyArea } from '../blast-radius-rules'
import { buildGhCreateArgs, missingTemplateHeadings, parseCreateArgs } from '../create-args'
import { findStickyComment, replaceManagedSection } from '../managed-content'
import { changedPackageFields, classifyPackageJsonChange } from '../package-json-risk'
import {
  renderReviewEvidenceComment,
  reviewEvidenceViolations,
  reviewedShaViolations,
} from '../review-evidence'

const SHA = 'c'.repeat(40)
const OTHER_SHA = 'd'.repeat(40)

describe('pr:create arguments', () => {
  it('always creates a draft against main with the body from a file', () => {
    const request = parseCreateArgs([
      '--title',
      'feat(agents): add skills',
      '--body-file',
      'body.md',
      '--label',
      'agents',
    ])

    expect(buildGhCreateArgs(request)).toEqual([
      'pr',
      'create',
      '--draft',
      '--base',
      'main',
      '--title',
      'feat(agents): add skills',
      '--body-file',
      'body.md',
      '--label',
      'agents',
    ])
  })

  it('keeps an explicit base and drops a duplicate draft flag', () => {
    const request = parseCreateArgs(['-t', 'fix: x', '-F', 'b.md', '-B', 'release', '--draft'])

    expect(request).toMatchObject({ base: 'release', passthrough: [] })
  })

  it('refuses an inline body, --fill and --web', () => {
    expect(() => parseCreateArgs(['--title', 'fix: x', '--body', 'text'])).toThrow(/--body-file/)
    expect(() => parseCreateArgs(['--fill'])).toThrow(/squash commit subject/)
    expect(() => parseCreateArgs(['--title', 'fix: x', '--body-file', 'b.md', '--web'])).toThrow(
      /terminal/,
    )
  })

  it('requires a title and a body file', () => {
    expect(() => parseCreateArgs(['--body-file', 'b.md'])).toThrow(/--title is required/)
    expect(() => parseCreateArgs(['--title', 'fix: x'])).toThrow(/--body-file is required/)
  })

  it('names the template sections a body dropped', () => {
    const template = '## Summary\n\ntext\n\n## Validation\n\n- [ ] check\n'

    expect(missingTemplateHeadings(template, '## Summary\n\nDid a thing.')).toEqual(['Validation'])
    expect(missingTemplateHeadings(template, '## summary\n## Validation')).toEqual([])
  })
})

describe('pr:ready review evidence', () => {
  it('accepts a reviewed SHA equal to HEAD and the PR head', () => {
    expect(reviewedShaViolations({ headSha: SHA, prHeadSha: SHA, reviewedSha: SHA })).toEqual([])
  })

  it('refuses a missing, short, stale or unpushed SHA', () => {
    expect(
      reviewedShaViolations({ headSha: SHA, prHeadSha: SHA, reviewedSha: undefined })[0],
    ).toMatch(/Missing/)
    expect(reviewedShaViolations({ headSha: SHA, prHeadSha: SHA, reviewedSha: 'ccc' })[0]).toMatch(
      /40-character/,
    )
    expect(
      reviewedShaViolations({ headSha: SHA, prHeadSha: SHA, reviewedSha: OTHER_SHA })[0],
    ).toMatch(/stale/)
    expect(
      reviewedShaViolations({ headSha: SHA, prHeadSha: OTHER_SHA, reviewedSha: SHA })[0],
    ).toMatch(/Push/)
  })

  it('requires the evidence to name the same SHA', () => {
    expect(reviewEvidenceViolations(`Rounds: 2\nreviewed-sha: ${SHA}\n`, SHA)).toEqual([])
    expect(reviewEvidenceViolations('Rounds: 2', SHA)[0]).toMatch(/reviewed-sha/)
    expect(reviewEvidenceViolations(`reviewed-sha: ${OTHER_SHA}`, SHA)[0]).toMatch(/different SHA/)
    expect(reviewEvidenceViolations('  ', SHA)[0]).toMatch(/empty/)
  })

  it('wraps the evidence in the AI notice and the review marker', () => {
    const comment = renderReviewEvidenceComment(`reviewed-sha: ${SHA}`)

    expect(comment.startsWith('> _This was generated by AI via the ready skill._')).toBe(true)
    expect(comment).toContain('<!-- openwaggle:code-review -->')
  })
})

describe('managed PR content', () => {
  const start = '<!-- s -->'
  const end = '<!-- /s -->'

  it('appends the section once and replaces it on later runs, keeping the rest', () => {
    const first = replaceManagedSection({
      body: '## Summary\n\nText',
      end,
      section: `${start}\nv1\n${end}`,
      start,
    })
    const second = replaceManagedSection({
      body: `${first}\n\n## Notes`,
      end,
      section: `${start}\nv2\n${end}`,
      start,
    })

    expect(first).toBe(`## Summary\n\nText\n\n${start}\nv1\n${end}`)
    expect(second).toBe(`## Summary\n\nText\n\n${start}\nv2\n${end}\n\n## Notes`)
  })

  it('finds only the sticky comment the viewer wrote', () => {
    const comments = [
      { author: 'someone', body: 'x <!-- m -->', id: 1 },
      { author: 'me', body: 'y <!-- m -->', id: 2 },
    ]

    expect(findStickyComment(comments, '<!-- m -->', 'me')?.id).toBe(2)
    expect(findStickyComment(comments, '<!-- m -->', 'nobody')).toBeUndefined()
  })
})

describe('blast radius', () => {
  it('rates the PR by its riskiest area and lists each area', () => {
    const changedFiles = parseNameStatus(
      'M\tsrc/main/ipc/x.ts\nA\tsrc/main/__tests__/x.unit.test.ts\nR100\tdocs/a.md\tdocs/b.md\nM\twebsite/src/x.astro',
    )
    const { report, risk, summary } = renderBlastRadius({
      changedFiles,
      headSha: SHA,
      packageJson: {},
      range: 'a...b',
    })

    expect(risk).toBe('High')
    expect(changedFiles[2]).toEqual({
      path: 'docs/b.md',
      previousPath: 'docs/a.md',
      status: 'R100',
    })
    expect(report).toContain('<!-- openwaggle:blast-radius-report -->')
    expect(report).toContain('Preload, IPC, auth and security (High, 1 file)')
    expect(report).toContain('Tests and fixtures (Medium, 1 file)')
    expect(summary('https://example.test/c')).toMatch(
      /^<!-- openwaggle:blast-radius -->[\s\S]*Full report: https:\/\/example\.test\/c[\s\S]*<!-- \/openwaggle:blast-radius -->$/,
    )
  })

  // A 5,000-file PR rendered a 352 KB report that GitHub refused with HTTP 422.
  it('shortens the file lists until the report fits in one GitHub comment', () => {
    const changedFiles = parseNameStatus(
      Array.from(
        { length: 6000 },
        (_, index) => `M\tsrc/main/some/long/path/file-${String(index)}.ts`,
      ).join('\n'),
    )
    const { report } = renderBlastRadius({
      changedFiles,
      headSha: SHA,
      packageJson: {},
      range: 'a...b',
    })

    expect(report.length).toBeLessThanOrEqual(GITHUB_COMMENT_MAX_CHARACTERS)
    expect(report).toContain('Main process (Medium, 6000 files)')
    expect(report).toMatch(/- … and \d+ files more: `git diff --name-status a\.\.\.b`/u)
  })

  it('lists every file when the report fits', () => {
    const changedFiles = parseNameStatus('M\tsrc/main/a.ts\nM\tsrc/main/b.ts')
    const { report } = renderBlastRadius({
      changedFiles,
      headSha: SHA,
      packageJson: {},
      range: 'a...b',
    })

    expect(report).toContain('- M `src/main/b.ts`')
    expect(report).not.toContain('more:')
  })

  // The lint and format configs moved from ESLint and Biome to oxlint, oxfmt and the Bun lint runner.
  it.each([
    'oxlint.config.mts',
    '.oxfmtrc.json',
    'tools/bun-lint/package.json',
    'tsconfig.node.json',
  ])('rates %s as build, lint and test configuration', (filePath) => {
    expect(classifyArea(filePath).key).toBe('tooling')
  })

  it('rates package.json by the fields that changed', () => {
    expect(
      classifyPackageJsonChange(changedPackageFields('{"scripts":{}}', '{"scripts":{"a":"b"}}'))
        .risk,
    ).toBe('Medium')
    expect(
      classifyPackageJsonChange(
        changedPackageFields('{"dependencies":{}}', '{"dependencies":{"a":"1"}}'),
      ).risk,
    ).toBe('High')
    expect(
      classifyPackageJsonChange(changedPackageFields('{"description":"a"}', '{"description":"b"}'))
        .risk,
    ).toBe('Low')
    expect(classifyPackageJsonChange(changedPackageFields('{}', 'not json')).risk).toBe('High')
  })
})
