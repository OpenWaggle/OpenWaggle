/**
 * Hidden HTML markers the PR scripts own. A marker lets a later run find and replace its own
 * text, and lets `pr:watch` treat these comments as reports rather than review comments.
 */
export const BLAST_RADIUS_SECTION_START = '<!-- openwaggle:blast-radius -->'
export const BLAST_RADIUS_SECTION_END = '<!-- /openwaggle:blast-radius -->'
export const BLAST_RADIUS_COMMENT_MARKER = '<!-- openwaggle:blast-radius-report -->'
export const CODE_REVIEW_COMMENT_MARKER = '<!-- openwaggle:code-review -->'

/** The notice that opens every comment an agent posts under the maintainer's account. */
export function aiNotice(skill: string) {
  return `> _This was generated by AI via the ${skill} skill._`
}

/**
 * Puts `section` (which carries its own start and end markers) in place of the managed section,
 * or at the end of the body when there is none yet. Text outside the markers is kept verbatim.
 */
export function replaceManagedSection(input: {
  readonly body: string
  readonly end: string
  readonly section: string
  readonly start: string
}) {
  const startIndex = input.body.indexOf(input.start)
  const endIndex = input.body.indexOf(input.end, startIndex)
  if (startIndex !== -1 && endIndex !== -1) {
    const before = input.body.slice(0, startIndex).trimEnd()
    const after = input.body.slice(endIndex + input.end.length).trimStart()
    return [before, input.section, after].filter((part) => part.length > 0).join('\n\n')
  }
  return [input.body.trimEnd(), input.section].filter((part) => part.length > 0).join('\n\n')
}

export interface IssueComment {
  readonly author: string
  readonly body: string
  readonly id: number
}

/** The viewer's own comment carrying `marker`, so a rerun edits it instead of posting again. */
export function findStickyComment(
  comments: readonly IssueComment[],
  marker: string,
  viewer: string,
) {
  return comments.findLast((comment) => comment.author === viewer && comment.body.includes(marker))
}
