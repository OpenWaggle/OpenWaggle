/**
 * Writes src/renderer/src/shared/lib/syntax/bundled-language-metadata.generated.ts: the id, name
 * and aliases of every language Shiki bundles. The renderer's language registry reads names and
 * aliases on the main thread; importing Shiki's `bundledLanguagesInfo` for them also referenced
 * every grammar's import thunk, so the main renderer build emitted all 244 grammar chunks
 * although only the syntax worker loads grammars (renderer-load.md, B10; ADR 0027 keeps every
 * language available there).
 *
 * Usage: `pnpm syntax-languages:generate` after a Shiki upgrade. The registry's unit test fails
 * while the file differs from the installed Shiki.
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs/promises'
import path from 'node:path'
import { bundledLanguagesInfo } from 'shiki'

export const SYNTAX_LANGUAGE_METADATA_PATH =
  'src/renderer/src/shared/lib/syntax/bundled-language-metadata.generated.ts'
const BIOME_LAUNCHER = 'node_modules/@biomejs/biome/bin/biome'
const FORMATTER_OUTPUT_LIMIT_BYTES = 16_777_216

export interface SyntaxLanguageMetadata {
  readonly id: string
  readonly name: string
  readonly aliases?: readonly string[]
}

export function syntaxLanguageMetadata(
  languages: readonly SyntaxLanguageMetadata[],
): readonly SyntaxLanguageMetadata[] {
  return languages.map(({ id, name, aliases }) =>
    aliases && aliases.length > 0 ? { id, name, aliases: [...aliases] } : { id, name },
  )
}

export function renderSyntaxLanguageMetadata(languages: readonly SyntaxLanguageMetadata[]) {
  return [
    '// Generated by scripts/generate-syntax-language-metadata.ts from Shiki\'s bundledLanguagesInfo.',
    '// Do not edit; run `pnpm syntax-languages:generate` after a Shiki upgrade.',
    "import type { BundledSyntaxLanguageMetadata } from './bundled-language-metadata'",
    '',
    'export const BUNDLED_SYNTAX_LANGUAGES: readonly BundledSyntaxLanguageMetadata[] = ',
    `${JSON.stringify(syntaxLanguageMetadata(languages))}`,
    '',
  ].join('\n')
}

function formatWithBiome(text: string, root: string) {
  return execFileSync(
    process.execPath,
    [path.join(root, BIOME_LAUNCHER), 'format', `--stdin-file-path=${SYNTAX_LANGUAGE_METADATA_PATH}`],
    { cwd: root, input: text, encoding: 'utf8', maxBuffer: FORMATTER_OUTPUT_LIMIT_BYTES },
  )
}

async function main() {
  const root = process.cwd()
  const output = formatWithBiome(renderSyntaxLanguageMetadata(bundledLanguagesInfo), root)
  await fs.writeFile(path.join(root, SYNTAX_LANGUAGE_METADATA_PATH), output)
  process.stdout.write(
    `Wrote ${String(bundledLanguagesInfo.length)} languages to ${SYNTAX_LANGUAGE_METADATA_PATH}\n`,
  )
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  void main().catch((error: unknown) => {
    console.error(error)
    process.exitCode = 1
  })
}
