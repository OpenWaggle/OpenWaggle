/**
 * The performance budgets file (`performance/perf-budgets.json`): counts and bytes measured from
 * fixed workloads, kept equal to the measurement (`bun run check`, the integration tier) and compared
 * with main's on every pull request (`.github/workflows/perf-gate.yml`).
 *
 * Each stored value is the measurement rounded up to the metric's quantum, so a change smaller
 * than one quantum leaves the file alone: fewer conflicts between pull requests, and no label for a
 * few bytes. The quantum is part of the file, so a coarser one is a raised limit the gate names.
 */
import fs from 'node:fs'
import path from 'node:path'
import { PERF_BUDGET_METRICS, type PerfBudgetMetric } from './budget-metrics'

export const PERF_BUDGETS_FILE = 'performance/perf-budgets.json'
/** Where an update run's measuring steps leave their values before they are merged. */
export const PERF_BUDGET_FRAGMENTS_ENV = 'OPENWAGGLE_PERF_BUDGETS_WRITE'

export interface PerfBudgetEntry {
  readonly value: number
  readonly quantum: number
}

export interface PerfBudgetFile {
  readonly about: string
  readonly metrics: Readonly<Record<string, PerfBudgetEntry>>
}

const ABOUT =
  "Generated by `bun run perf:budgets:update` from fixed workloads; do not edit. `bun run check` and the integration tier fail when a value differs from the measurement, and the Performance Gate fails a pull request that raises a value above main's unless it carries the perf-budget-increase label (.agents/memory/performance.md)."
const JSON_INDENT = 2

function isRecord(value: unknown): value is Readonly<Record<string, unknown>> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function isEntry(value: unknown): value is PerfBudgetEntry {
  return (
    isRecord(value) &&
    Number.isSafeInteger(value['value']) &&
    Number.isSafeInteger(value['quantum']) &&
    Number(value['quantum']) > 0
  )
}

/** Parses a budgets file, rejecting anything but integer values and positive integer quanta. */
export function parsePerfBudgetFile(text: string, source: string): PerfBudgetFile {
  const parsed: unknown = JSON.parse(text)
  if (!isRecord(parsed) || !isRecord(parsed['metrics'])) {
    throw new Error(`${source} has no metrics object.`)
  }
  const metrics: Record<string, PerfBudgetEntry> = {}
  for (const [id, entry] of Object.entries(parsed['metrics'])) {
    if (!isEntry(entry)) throw new Error(`${source}: ${id} is not { value, quantum } integers.`)
    metrics[id] = { value: entry.value, quantum: entry.quantum }
  }
  return { about: typeof parsed['about'] === 'string' ? parsed['about'] : '', metrics }
}

export function readPerfBudgetFile(root = process.cwd()): PerfBudgetFile {
  const file = path.join(root, PERF_BUDGETS_FILE)
  return parsePerfBudgetFile(fs.readFileSync(file, 'utf8'), PERF_BUDGETS_FILE)
}

/** The measurement as the file stores it: rounded up to a multiple of the quantum. */
export function quantize(measured: number, quantum: number) {
  return Math.ceil(measured / quantum) * quantum
}

export function metricById(id: string): PerfBudgetMetric {
  const metric = PERF_BUDGET_METRICS.find((candidate) => candidate.id === id)
  if (metric === undefined) throw new Error(`No performance budget metric ${id}.`)
  return metric
}

/** The file for these measurements, in registry order. */
export function perfBudgetFileFor(measured: Readonly<Record<string, number>>): PerfBudgetFile {
  const metrics: Record<string, PerfBudgetEntry> = {}
  for (const metric of PERF_BUDGET_METRICS) {
    const value = measured[metric.id]
    if (value === undefined) throw new Error(`No measurement for ${metric.id}.`)
    metrics[metric.id] = { value: quantize(value, metric.quantum), quantum: metric.quantum }
  }
  return { about: ABOUT, metrics }
}

export function formatPerfBudgetFile(file: PerfBudgetFile) {
  return `${JSON.stringify(file, null, JSON_INDENT)}\n`
}

export interface PerfBudgetMismatch {
  readonly id: string
  readonly stored: number | undefined
  readonly measured: number
  readonly message: string
}

/** Where `measured` (raw values) and the file disagree, with what to run. */
export function perfBudgetMismatches(
  file: PerfBudgetFile,
  measured: Readonly<Record<string, number>>,
): PerfBudgetMismatch[] {
  return Object.entries(measured).flatMap(([id, raw]) => {
    const metric = metricById(id)
    const entry = file.metrics[id]
    const value = quantize(raw, metric.quantum)
    if (entry?.value === value && entry.quantum === metric.quantum) return []
    const stored = entry?.value
    const direction = stored === undefined ? 'is missing' : value > stored ? 'went up' : 'went down'
    return [
      {
        id,
        stored,
        measured: value,
        message:
          `${PERF_BUDGETS_FILE} ${id} ${direction}: stored ${String(stored ?? '-')}, measured ${String(value)} ` +
          `(${String(raw)} before rounding to ${String(metric.quantum)}). ` +
          (stored !== undefined && value > stored
            ? `${metric.fix} If the increase is intended, run bun run perf:budgets:update; the Performance Gate then needs the perf-budget-increase label.`
            : 'Run bun run perf:budgets:update and commit the file.'),
      },
    ]
  })
}

/** Metrics the registry and the file do not agree on: a stale or missing key, a changed quantum. */
export function perfBudgetShapeProblems(file: PerfBudgetFile) {
  const registered = new Set(PERF_BUDGET_METRICS.map((metric) => metric.id))
  const stale = Object.keys(file.metrics)
    .filter((id) => !registered.has(id))
    .map((id) => `${PERF_BUDGETS_FILE} has ${id}, which no measurement writes.`)
  const missing = PERF_BUDGET_METRICS.filter((metric) => file.metrics[metric.id] === undefined).map(
    (metric) => `${PERF_BUDGETS_FILE} lacks ${metric.id}.`,
  )
  const quanta = PERF_BUDGET_METRICS.filter((metric) => {
    const entry = file.metrics[metric.id]
    return entry !== undefined && entry.quantum !== metric.quantum
  }).map((metric) => `${PERF_BUDGETS_FILE} ${metric.id} quantum differs from budget-metrics.ts.`)
  const problems = [...stale, ...missing, ...quanta]
  return problems.length === 0
    ? []
    : [...problems, 'Run bun run perf:budgets:update and commit the file.']
}

/**
 * Called by a measuring step or test with its raw values. During `perf:budgets:update` it writes
 * them as a fragment for the update to merge; otherwise it returns the mismatches with the file.
 */
export function recordPerfMeasurements(
  group: string,
  measured: Readonly<Record<string, number>>,
  environment: Readonly<Record<string, string | undefined>> = process.env,
  root = process.cwd(),
): PerfBudgetMismatch[] {
  const fragments = environment[PERF_BUDGET_FRAGMENTS_ENV]
  if (fragments !== undefined && fragments !== '') {
    fs.mkdirSync(fragments, { recursive: true })
    fs.writeFileSync(path.join(fragments, `${group}.json`), JSON.stringify(measured))
    return []
  }
  return perfBudgetMismatches(readPerfBudgetFile(root), measured)
}
